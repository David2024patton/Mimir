// Package critic implements Mímir's built-in Epistemic Critic & Verification Node.
// It audits generator outputs (<draft_report>) against retrieved evidence
// (<retrieved_context>: tool outputs, repo files, scraped docs) to isolate
// UNVERIFIED_TRAINING_DATA, EXTRAPOLATION, vendor bias, and hype/overstatement,
// and computes a deterministic pass_audit routing verdict.
package critic

import (
	"context"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"

	"github.com/David2024patton/Mimir/internal/llm"
)

// SourceStatus classifies how a claim relates to <retrieved_context>.
const (
	StatusUnverifiedTrainingData = "UNVERIFIED_TRAINING_DATA"
	StatusExtrapolation          = "EXTRAPOLATION"
	StatusVendorClaim            = "VENDOR_CLAIM"
	StatusHypeOverstatement      = "HYPE_OVERSTATEMENT"
)

// Severity levels for unbacked claims.
const (
	SeverityHigh   = "HIGH"
	SeverityMedium = "MEDIUM"
	SeverityLow    = "LOW"
)

// Confidence Rubric levels for takeaways.
const (
	ConfidenceHigh   = "HIGH"
	ConfidenceMedium = "MEDIUM"
	ConfidenceLow    = "LOW"
)

// EpistemicPrompt is the canonical system prompt for Mímir's Epistemic Critic & Verification Node.
const EpistemicPrompt = `# ROLE & OBJECTIVE
You are an Epistemic Critic & Verification Node within an autonomous agent harness. Your sole objective is to audit the Generator Agent's output against the provided <retrieved_context> (search results, scraped docs, or tool outputs) and identify unsupported claims, vendor bias, and overstated certainty.

# INPUT DATA EXPECTATIONS
You will receive a payload containing:
1. <retrieved_context>: The raw sources, snippets, and data retrieved during the session.
2. <draft_report>: The synthesized report generated by the upstream agent.

# AUDIT RULES
1. Zero Fabrication of Flaws: If a category has zero violations, return an empty array []. Do not invent minor nitpicks to appear thorough.
2. Strict Source Grounding: Any claim, statistic, or technical specification in <draft_report> not explicitly present in <retrieved_context> must be flagged as UNVERIFIED_TRAINING_DATA or EXTRAPOLATION.
3. Vendor Bias Isolation: Any benchmark, performance metric, or pricing advantage originating from a first-party vendor blog, press release, or marketing page must be flagged.
4. Hype Stripping: Flag any absolute language ("always", "guaranteed", "industry-leading", "10x faster") where caveats or testing conditions were omitted.
5. Routing Logic: Set pass_audit to false if there are any HIGH severity unbacked claims or if more than 2 takeaways score LOW confidence.

# CONFIDENCE RUBRIC
- HIGH: Backed by multiple independent sources in <retrieved_context> or hard empirical/reproducible data.
- MEDIUM: Backed by a single credible source in <retrieved_context> or strong technical consensus with minor caveats.
- LOW: Vendor claim only, extrapolated data, or relies on unverified training-data assumptions.`

// UnbackedClaim represents a claim in <draft_report> not grounded in <retrieved_context>.
type UnbackedClaim struct {
	Claim          string `json:"claim"`
	Classification string `json:"classification"` // UNVERIFIED_TRAINING_DATA | EXTRAPOLATION
	Severity       string `json:"severity"`       // HIGH | MEDIUM | LOW
	Reason         string `json:"reason"`
	Correction     string `json:"correction"`
}

// VendorBiasFlag represents a number or benchmark originating from a vendor/promotional source.
type VendorBiasFlag struct {
	Figure       string `json:"figure"`
	VendorOrigin string `json:"vendor_origin"`
	Caveat       string `json:"caveat"`
}

// HypeFlag represents absolute or overstated language stripped of caveats.
type HypeFlag struct {
	Phrase      string `json:"phrase"`
	Issue       string `json:"issue"`
	Replacement string `json:"replacement"`
}

// AuditedTakeaway represents a corrected takeaway graded against the Confidence Rubric.
type AuditedTakeaway struct {
	Index             int    `json:"index"`
	CorrectedTakeaway string `json:"corrected_takeaway"`
	Confidence        string `json:"confidence"` // HIGH | MEDIUM | LOW
	EvidenceBasis     string `json:"evidence_basis"`
}

// AuditReport is the structured output of the Epistemic Critic & Verification Node.
type AuditReport struct {
	PassAudit          bool              `json:"pass_audit"`
	RoutingReason      string            `json:"routing_reason"`
	UnbackedClaims     []UnbackedClaim   `json:"unbacked_claims"`
	VendorBiasFlags    []VendorBiasFlag  `json:"vendor_bias_flags"`
	HypeFlags          []HypeFlag        `json:"hype_flags"`
	CorrectedTakeaways []AuditedTakeaway `json:"corrected_takeaways"`
}

// ApplyRoutingRule enforces Audit Rule #5 deterministically:
// Set pass_audit to false if there are any HIGH severity unbacked claims
// or if more than 2 takeaways score LOW confidence.
func (r *AuditReport) ApplyRoutingRule() {
	if r.UnbackedClaims == nil {
		r.UnbackedClaims = []UnbackedClaim{}
	}
	if r.VendorBiasFlags == nil {
		r.VendorBiasFlags = []VendorBiasFlag{}
	}
	if r.HypeFlags == nil {
		r.HypeFlags = []HypeFlag{}
	}
	if r.CorrectedTakeaways == nil {
		r.CorrectedTakeaways = []AuditedTakeaway{}
	}

	highUnbacked := 0
	for _, c := range r.UnbackedClaims {
		if strings.EqualFold(c.Severity, SeverityHigh) {
			highUnbacked++
		}
	}
	lowTakeaways := 0
	for _, t := range r.CorrectedTakeaways {
		if strings.EqualFold(t.Confidence, ConfidenceLow) {
			lowTakeaways++
		}
	}

	if highUnbacked > 0 || lowTakeaways > 2 {
		r.PassAudit = false
		r.RoutingReason = fmt.Sprintf("FAILED routing gate: %d HIGH-severity unbacked claims (max 0) and %d LOW-confidence takeaways (max 2)", highUnbacked, lowTakeaways)
	} else {
		r.PassAudit = true
		r.RoutingReason = fmt.Sprintf("PASSED routing gate: 0 HIGH-severity unbacked claims and %d LOW-confidence takeaways (<=2)", lowTakeaways)
	}
}

var (
	reNumbers = regexp.MustCompile(`(?i)(\$[0-9,.]+(?:/mo|/day|/yr)?|[0-9]+(?:\.[0-9]+)?%|<?[0-9]+(?:\.[0-9]+)?m?s\b|[0-9]+(?:\.[0-9]+)?x\s+faster)`)
	hypeTerms = []struct {
		phrase      string
		issue       string
		replacement string
	}{
		{"guaranteed", "Absolute guarantee without controlled test conditions", "designed to support (subject to environment and workload)"},
		{"industry-leading", "Unmeasured superlative marketing phrasing", "specialized for this workflow"},
		{"10x faster", "Unbenchmarked multiplier without baseline hardware/dataset context", "reduces latency overhead in targeted steps (benchmark against your workload)"},
		{"3-5x faster", "Estimated speedup without controlled A/B timing logs in retrieved context", "reduces token generation overhead on follow-up tool steps"},
		{"unquestionably", "Overstated certainty", "in the reviewed sources"},
		{"zero latency", "Physical impossibility; heuristic execution still takes microseconds/milliseconds", "sub-millisecond local heuristic execution"},
	}
)

// AuditDeterministic runs a fast, deterministic epistemic audit comparing <draft_report>
// against <retrieved_context>, isolating numbers/claims absent from context, vendor claims,
// and hype phrases, then applying Audit Rule #5.
func AuditDeterministic(retrievedContext, draftReport string) AuditReport {
	report := AuditReport{
		UnbackedClaims:     []UnbackedClaim{},
		VendorBiasFlags:    []VendorBiasFlag{},
		HypeFlags:          []HypeFlag{},
		CorrectedTakeaways: []AuditedTakeaway{},
	}

	ctxLower := strings.ToLower(retrievedContext)
	draftLines := strings.Split(draftReport, "\n")

	// 1. Check numbers/metrics in <draft_report> against <retrieved_context>
	seenMetrics := map[string]bool{}
	for _, line := range draftLines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		matches := reNumbers.FindAllString(trimmed, -1)
		for _, m := range matches {
			mLower := strings.ToLower(m)
			if seenMetrics[mLower] {
				continue
			}
			seenMetrics[mLower] = true

			if !strings.Contains(ctxLower, mLower) {
				sev := SeverityMedium
				if strings.Contains(mLower, "%") || strings.Contains(mLower, "faster") || strings.Contains(mLower, "ms") {
					sev = SeverityHigh
				}
				report.UnbackedClaims = append(report.UnbackedClaims, UnbackedClaim{
					Claim:          fmt.Sprintf("%s (in: %q)", m, truncate(trimmed, 110)),
					Classification: StatusUnverifiedTrainingData,
					Severity:       sev,
					Reason:         fmt.Sprintf("Metric %q appears in <draft_report> but is not present in <retrieved_context>.", m),
					Correction:     "Remove unverified metric or label explicitly as an unbenchmarked design target / illustrative example.",
				})
			} else if strings.Contains(strings.ToLower(trimmed), "vendor") ||
				strings.Contains(strings.ToLower(trimmed), "survey") ||
				strings.Contains(strings.ToLower(trimmed), "benchmark") ||
				strings.Contains(strings.ToLower(trimmed), "merchant") ||
				strings.Contains(strings.ToLower(trimmed), "brightlocal") ||
				strings.Contains(strings.ToLower(trimmed), "wordstream") {
				report.VendorBiasFlags = append(report.VendorBiasFlags, VendorBiasFlag{
					Figure:       m,
					VendorOrigin: truncate(trimmed, 100),
					Caveat:       "First-party vendor/survey figure; not an independent audited causal result.",
				})
			}
		}

		// 2. Hype stripping check (Audit Rule #4)
		lowerLine := strings.ToLower(trimmed)
		for _, ht := range hypeTerms {
			if strings.Contains(lowerLine, ht.phrase) {
				report.HypeFlags = append(report.HypeFlags, HypeFlag{
					Phrase:      ht.phrase,
					Issue:       ht.issue,
					Replacement: ht.replacement,
				})
			}
		}
	}

	report.ApplyRoutingRule()
	return report
}

// AuditWithLLM runs the full Epistemic Critic prompt via the configured LLM provider
// when available, falling back to AuditDeterministic if the provider is nil or fails.
func AuditWithLLM(ctx context.Context, provider llm.Provider, model, retrievedContext, draftReport string) (AuditReport, error) {
	det := AuditDeterministic(retrievedContext, draftReport)
	if provider == nil || model == "" {
		return det, nil
	}

	payload := fmt.Sprintf("<retrieved_context>\n%s\n</retrieved_context>\n\n<draft_report>\n%s\n</draft_report>\n\nReturn ONLY valid JSON matching AuditReport schema: {\"pass_audit\":bool,\"routing_reason\":string,\"unbacked_claims\":[{\"claim\":string,\"classification\":string,\"severity\":string,\"reason\":string,\"correction\":string}],\"vendor_bias_flags\":[{\"figure\":string,\"vendor_origin\":string,\"caveat\":string}],\"hype_flags\":[{\"phrase\":string,\"issue\":string,\"replacement\":string}],\"corrected_takeaways\":[{\"index\":int,\"corrected_takeaway\":string,\"confidence\":string,\"evidence_basis\":string}]}",
		retrievedContext, draftReport)

	resp, err := provider.Generate(ctx, llm.GenerateRequest{
		Model: model,
		Messages: []llm.Message{
			{Role: "system", Content: EpistemicPrompt},
			{Role: "user", Content: payload},
		},
		Effort: "low",
	})
	if err != nil {
		return det, nil
	}

	repaired := llm.RepairJSON(extractJSONBlock(resp.Content))
	var parsed AuditReport
	if err := json.Unmarshal([]byte(repaired), &parsed); err != nil {
		return det, nil
	}
	parsed.ApplyRoutingRule()
	return parsed, nil
}

// FormatMarkdown renders the AuditReport as a clean Markdown report.
func (r AuditReport) FormatMarkdown() string {
	var b strings.Builder
	verdict := "PASS (`pass_audit: true`)"
	if !r.PassAudit {
		verdict = "FAIL / REVISE (`pass_audit: false`)"
	}
	fmt.Fprintf(&b, "## Epistemic Critic & Verification Node Verdict: %s\n", verdict)
	fmt.Fprintf(&b, "- **Routing Gate**: %s\n\n", r.RoutingReason)

	fmt.Fprintf(&b, "### 1. Unbacked Claims (`%d`)\n", len(r.UnbackedClaims))
	if len(r.UnbackedClaims) == 0 {
		b.WriteString("`[]` (Zero violations)\n\n")
	} else {
		for _, c := range r.UnbackedClaims {
			fmt.Fprintf(&b, "- **[%s | Severity: %s]** %s\n  - *Reason*: %s\n  - *Correction*: %s\n",
				c.Classification, c.Severity, c.Claim, c.Reason, c.Correction)
		}
		b.WriteString("\n")
	}

	fmt.Fprintf(&b, "### 2. Vendor Bias Flags (`%d`)\n", len(r.VendorBiasFlags))
	if len(r.VendorBiasFlags) == 0 {
		b.WriteString("`[]` (Zero violations)\n\n")
	} else {
		for _, v := range r.VendorBiasFlags {
			fmt.Fprintf(&b, "- **%s** -- *Origin*: %s\n  - *Caveat*: %s\n", v.Figure, v.VendorOrigin, v.Caveat)
		}
		b.WriteString("\n")
	}

	fmt.Fprintf(&b, "### 3. Hype & Overstatement Flags (`%d`)\n", len(r.HypeFlags))
	if len(r.HypeFlags) == 0 {
		b.WriteString("`[]` (Zero violations)\n\n")
	} else {
		for _, h := range r.HypeFlags {
			fmt.Fprintf(&b, "- **%q** -> *Issue*: %s | *Replace with*: %q\n", h.Phrase, h.Issue, h.Replacement)
		}
		b.WriteString("\n")
	}

	if len(r.CorrectedTakeaways) > 0 {
		b.WriteString("### 4. Corrected Takeaways & Confidence Rubric\n")
		for _, t := range r.CorrectedTakeaways {
			fmt.Fprintf(&b, "%d. **[%s]** %s\n   - *Evidence Basis*: %s\n",
				t.Index, t.Confidence, t.CorrectedTakeaway, t.EvidenceBasis)
		}
	}
	return strings.TrimSpace(b.String())
}

func truncate(s string, max int) string {
	if len(s) <= max {
		return s
	}
	return s[:max] + "..."
}

func extractJSONBlock(s string) string {
	s = strings.TrimSpace(s)
	if start := strings.Index(s, "{"); start >= 0 {
		if end := strings.LastIndex(s, "}"); end > start {
			return s[start : end+1]
		}
	}
	return s
}
